// One-off helper: generates a fresh throwaway wallet for deploying BeatChart
// to Monad testnet, and appends its private key to .env.local (gitignored —
// never committed, never printed again after this run). Only the address is
// printed, so it can be funded from https://faucet.monad.xyz.
//
// Run once with: node scripts/generate-deployer.js
const fs = require("fs");
const path = require("path");
const { ethers } = require("ethers");

const envPath = path.join(__dirname, "..", ".env.local");
const existing = fs.existsSync(envPath) ? fs.readFileSync(envPath, "utf8") : "";

if (/^DEPLOYER_PRIVATE_KEY=.+$/m.test(existing)) {
  const wallet = new ethers.Wallet(existing.match(/^DEPLOYER_PRIVATE_KEY=(.+)$/m)[1].trim());
  console.log("DEPLOYER_PRIVATE_KEY already set in .env.local — reusing it.");
  console.log("Deployer address:", wallet.address);
  process.exit(0);
}

const wallet = ethers.Wallet.createRandom();
const addition =
  "\n# Throwaway Monad-testnet-only deployer key — generated by scripts/generate-deployer.js.\n" +
  "# Never reused anywhere else, never committed (this file is gitignored).\n" +
  `DEPLOYER_PRIVATE_KEY=${wallet.privateKey}\n`;

fs.appendFileSync(envPath, addition);

console.log("Generated a new deployer wallet and saved its key to .env.local.");
console.log("Deployer address:", wallet.address);
console.log("Fund it with testnet MON at https://faucet.monad.xyz, then run the deploy script.");
